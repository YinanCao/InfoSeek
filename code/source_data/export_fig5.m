% EXPORT_FIG5  Write the Source Data for Figure 5 to source_data/SourceData_Fig5.xlsx.
%
% Runs the finalized figure script code/figures/fig5.m unchanged, then writes one
% sheet per panel (a-c: match, d-f: guess). Set Nsim = 1000 in fig5.m before
% running, so that the Source Data and the published figure come from the same
% 1,000 simulations per participant, condition and knockout type.
%
% Usage (from any folder):
%   run('<path to InfoSeek_clean>/code/source_data/export_fig5.m')

addpath(fileparts(mfilename('fullpath')));   % helper functions sd_*.m
run(fullfile(fileparts(fileparts(fileparts(mfilename('fullpath')))), 'setup_paths.m'));
fig5;   % finalized figure script; note that it clears the workspace

root    = fileparts(fileparts(fileparts(mfilename('fullpath'))));
outfile = fullfile(root, 'source_data', 'SourceData_Fig5.xlsx');
if isfile(outfile), delete(outfile); end
if Nsim < 1000
    warning('export_fig5:Nsim', 'Nsim = %d in fig5.m; the Source Data should use Nsim = 1000.', Nsim);
end

pid        = unique_ids(:);
cond_name  = {'match', 'guess'};
model_name = {'exact', 'leak', 'noise', 'leak + noise (full)'};          % order of elbo_run
ko_order   = [1 3 2 4];                                                 % order of the knockout bars
ko_name    = {'KO leak & noise', 'KO leak', 'KO noise', 'full'};
panel      = {'Fig5a', 'Fig5b', 'Fig5c'; 'Fig5d', 'Fig5e', 'Fig5f'};    % rows: match, guess
chk        = struct();

%% README -----------------------------------------------------------------
sd_readme(outfile, {
  'Source Data for Figure 5 (Model comparison and simulations).'
  'Generated by code/source_data/export_fig5.m from the figure script code/figures/fig5.m (https://github.com/YinanCao/InfoSeek).'
  sprintf('n = %d participants. "participant" is the anonymised participant number used in the data files.', nsubj)
  'Top row (match): Fig5a, Fig5b, Fig5c. Bottom row (guess): Fig5d, Fig5e, Fig5f.'
  ''
  'Sheets'
  'Fig5a, Fig5d: random-effects Bayesian model selection. Posterior mean model frequency with 95% Bayesian credible interval (10,000 draws from the Dirichlet posterior), protected exceedance probability, Dirichlet parameters (alpha) and Bayesian omnibus risk (BOR). Participant level: ELBO (log model evidence) of each model, the input to the model selection.'
  'Fig5b, Fig5e: family-wise comparisons. Posterior mean frequency of the family with leak (leak vs. no leak) and with noise (noise vs. no noise), with 95% credible intervals. Input: the participant-level ELBO values in Fig5a and Fig5d.'
  sprintf('Fig5c, Fig5f: left, accuracy of the full model (mean over %d simulations per participant) and human accuracy by sequence length; right, mean accuracy over sequence lengths for each knockout model and for humans (bars and dots in the figure). Match accuracy: last choice in games where the two bags are linked to opposite colours; guess accuracy: final-probe (out-of-sample) inference.', Nsim)
  '95% CI = mean +/- 1.96 x SD / sqrt(n) across participants, as plotted.'
  });

for c = 1:2
    %% Fig 5a / 5d: model frequencies -------------------------------------------
    sh = panel{c,1}; r = 1; chk.(sh) = 0;
    S = table(model_name', pavg_mod(c,:)', credint_lower(c,:)', credint_upper(c,:)', pexc_mod(c,:)', alphas(c,:)', ...
              'VariableNames', {'model','posterior_mean_frequency','CI95_lower','CI95_upper','protected_exceedance_probability','dirichlet_alpha'});
    S = sd_label(S, {'condition'}, {cond_name{c}});
    [r, chk.(sh)] = sd_block(outfile, sh, r, sprintf('Summary, %s: posterior model frequencies (Bayesian omnibus risk, BOR = %.3g)', cond_name{c}, bor(c)), S, chk.(sh));
    T = [table(pid, 'VariableNames', {'participant'}), ...
         array2table(squeeze(elbo_run(:, c, :)), 'VariableNames', strcat({'ELBO_'}, {'exact','leak','noise','leak_noise_full'}))];
    [~, chk.(sh)] = sd_block(outfile, sh, r, sprintf('Participant level, %s: ELBO of each model', cond_name{c}), T, chk.(sh));

    %% Fig 5b / 5e: family comparisons --------------------------------------------
    sh = panel{c,2}; r = 1; chk.(sh) = 0;
    S = table({'with leak (leak vs. no leak)'; 'with noise (noise vs. no noise)'}, pavg_mod_fac(c,:)', ...
              credint_lower_fac(c,:)', credint_upper_fac(c,:)', ...
              'VariableNames', {'family','posterior_mean_frequency','CI95_lower','CI95_upper'});
    S = sd_label(S, {'condition'}, {cond_name{c}});
    [~, chk.(sh)] = sd_block(outfile, sh, r, sprintf('Summary, %s: family-wise posterior frequencies (input: participant-level ELBO in sheet %s)', cond_name{c}, panel{c,1}), S, chk.(sh));

    %% Fig 5c / 5f: model-predicted vs human accuracy and knockouts ---------------
    sh = panel{c,3}; r = 1; chk.(sh) = 0;
    if c == 1, acc_h = drawPc_human; acc_m = drawPc_model; else, acc_h = guessPc_human; acc_m = guessPc_model; end
    S = [sd_label(sd_summary(acc_m(:,:,4), 'sequence_length', seqLength), {'data'}, {'model (leak + noise, full)'}); ...
         sd_label(sd_summary(acc_h,        'sequence_length', seqLength), {'data'}, {'human'})];
    [r, chk.(sh)] = sd_block(outfile, sh, r, sprintf('Summary, left, %s: accuracy by sequence length', cond_name{c}), S, chk.(sh));
    T = [table(pid, 'VariableNames', {'participant'}), ...
         sd_label(array2table(acc_m(:,:,4), 'VariableNames', sd_names('length_%d', seqLength)), {'data'}, {'model (leak + noise, full)'}); ...
         table(pid, 'VariableNames', {'participant'}), ...
         sd_label(array2table(acc_h, 'VariableNames', sd_names('length_%d', seqLength)), {'data'}, {'human'})];
    [r, chk.(sh)] = sd_block(outfile, sh, r, sprintf('Participant level, left, %s: accuracy by sequence length', cond_name{c}), T, chk.(sh));
    Mko = squeeze(mean(acc_m(:,:,ko_order), 2, 'omitnan'));   % participants x knockout type, mean over lengths
    Mh  = mean(acc_h, 2);
    S = sd_summary([Mko, Mh], 'model', 1:5);
    S.model = [ko_name, {'human'}]';
    [r, chk.(sh)] = sd_block(outfile, sh, r, sprintf('Summary, right, %s: mean accuracy over sequence lengths', cond_name{c}), S, chk.(sh));
    T = [table(pid, 'VariableNames', {'participant'}), ...
         array2table([Mko, Mh], 'VariableNames', {'KO_leak_and_noise','KO_leak','KO_noise','full','human'})];
    [~, chk.(sh)] = sd_block(outfile, sh, r, sprintf('Participant level, right, %s: mean accuracy over sequence lengths', cond_name{c}), T, chk.(sh));
end

%% Read-back check ------------------------------------------------------------
sd_readback(outfile, chk);
