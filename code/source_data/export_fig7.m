run(fullfile(fileparts(fileparts(fileparts(mfilename('fullpath')))), 'setup_paths.m'));

%% ===================== Part 1: Fig. 7a-d (fig7abcd.m) =====================
fig7abcd;   % finalized figure script; note that it clears the workspace

root    = fileparts(fileparts(fileparts(mfilename('fullpath'))));
outfile = fullfile(root, 'source_data', 'SourceData_Fig7.xlsx');
if isfile(outfile), delete(outfile); end

pid       = unique_ids(:);
N         = numel(pid);                 % fig7abcd.m reuses nsubj for subgroup sizes
grp       = ToC(:, 2);                  % 1 = streaking, 0 = non-streaking (guess-condition ELBO)
gname     = {'non-streaking', 'streaking'};
glab      = gname(grp + 1); glab = glab(:);
cond_name = {'match', 'guess'};
chk       = struct();

sd_readme(outfile, {
  'Source Data for Figure 7 (Distinct behaviors by early-streaking tendency).'
  'Generated by code/source_data/export_fig7.m from the figure scripts code/figures/fig7abcd.m and code/figures/fig7efgh.m (https://github.com/YinanCao/InfoSeek).'
  sprintf('Fig7a-d: n = %d participants (main experiment), %d streaking and %d non-streaking. "participant" is the anonymised participant number used in the data files.', N, sum(grp == 1), sum(grp == 0))
  'Subgroups: streaking if the model with a free initial threshold theta has a higher ELBO than the model with theta fixed at 0 in the guess condition (dELBO_guess_EoS > 0); the same grouping is used for both conditions.'
  'Group contrasts are streaking minus non-streaking (two-sided Welch t-tests).'
  'Empty cells: no data.'
  ''
  'Sheets'
  'Fig7a: random-effects Bayesian model selection between the models with free theta and with theta fixed at 0 (posterior mean model frequency, 95% credible interval from 10,000 Dirichlet draws, protected exceedance probability), group-level log10 Bayes factor with 95% bootstrap CI (10,000 resamples, rng(45), as in fig7abcd.m), and participant-level ELBO values.'
  'Fig7b: p(repeat next) by times the current option was seen before, by subgroup and condition. 95% CI = mean +/- 1.96 x SD / sqrt(n with data at each point), as plotted. Thick lines: q_FDR < 0.005 (Benjamini-Hochberg across all times-seen values, as in fig7abcd.m).'
  'Fig7c: policy alignment by subgroup: target-guided (match) and uncertainty-guided (guess), sampling trials 2 to 20. 95% CI = mean +/- 1.96 x SD / sqrt(subgroup size), as plotted. Thick lines: q_FDR < 0.005 across trials.'
  'Fig7d: accuracy by sequence length and subgroup (match: last choice in games where the two bags are linked to opposite colours; guess: final probe). 95% CI as plotted. Tests: Welch t-tests with Holm-Bonferroni correction across the four lengths (asterisks: P_Holm < 0.05); the mean over lengths is tested separately (uncorrected).'
  'Fig7e-h: cued-choice experiment (guess condition only); see the n and the condition names in each sheet. Conditions: free choice, cued streaking (S), cued non-streaking (NS).'
  'Fig7e: p(repeat next) by times seen before. Fig7f: uncertainty-guided policy alignment. 95% CI = mean +/- 1.96 x SD / sqrt(n with data at each point), as plotted.'
  'Fig7g: guess accuracy by sequence length, mean +/- 1 SEM (as plotted). Tests: cued S minus cued NS, two-sided paired t-tests, Holm-Bonferroni across the four lengths; the mean over lengths is tested separately (uncorrected).'
  'Fig7h: mean guess accuracy over sequence lengths (bars, 95% CI) and planned contrasts against cued NS (two-sided paired t-tests, Holm-Bonferroni across the two contrasts).'
  });

%% Fig 7a ---------------------------------------------------------------------
sh = 'Fig7a'; r = 1; chk.(sh) = 0;
S = table();
for c = 1:2
    S = [S; table(repmat(cond_name(c), 2, 1), {'free theta'; 'fixed theta = 0'}, pavg_mod(c,:)', ...
                  credint_lower(c,:)', credint_upper(c,:)', pexc_mod(c,:)', alphas(c,:)', ...
                  'VariableNames', {'condition','model','posterior_mean_frequency','CI95_lower','CI95_upper', ...
                                    'protected_exceedance_probability','dirichlet_alpha'})]; %#ok<AGROW>
end
[r, chk.(sh)] = sd_block(outfile, sh, r, 'Summary: posterior model frequencies, free theta vs. theta fixed at 0', S, chk.(sh));
S = table();
for c = 1:2
    lme = squeeze(elbo(:, c, :));
    dl  = lme(:, 1) - lme(:, 2);
    rng(45); B = 10000; n = size(lme, 1); bb = zeros(B, 1);
    for b = 1:B
        ib = randsample(n, n, true);
        bb(b) = sum(lme(ib, 1) - lme(ib, 2)) / log(10);
    end
    cib = quantile(bb, [0.025 0.975]);
    S = [S; table(cond_name(c), n, sum(dl > 0), sum(dl) / log(10), cib(1), cib(2), ...
                  'VariableNames', {'condition','n','n_dELBO_positive','log10BF_free_vs_fixed_theta', ...
                                    'CI95_lower_bootstrap','CI95_upper_bootstrap'})]; %#ok<AGROW>
end
[r, chk.(sh)] = sd_block(outfile, sh, r, 'Summary: group-level log10 Bayes factor (sum of dELBO / ln 10) with bootstrap 95% CI', S, chk.(sh));
T = table(pid, glab, elbo(:,1,1), elbo(:,1,2), elbo(:,1,1) - elbo(:,1,2), elbo(:,2,1), elbo(:,2,2), elbo(:,2,1) - elbo(:,2,2), ...
          'VariableNames', {'participant','group','ELBO_free_theta_match','ELBO_fixed_theta_match','dELBO_match', ...
                            'ELBO_free_theta_guess','ELBO_fixed_theta_guess','dELBO_guess_EoS'});
[~, chk.(sh)] = sd_block(outfile, sh, r, 'Participant level: ELBO of each model and dELBO (free minus fixed theta)', T, chk.(sh));

%% Fig 7b ---------------------------------------------------------------------
sh = 'Fig7b'; r = 1; chk.(sh) = 0;
Xs = 1:10;
S = table(); C = table(); T = table();
for c = [2 1]
    for gi = [1 0]
        D = prepeat(grp == gi, Xs, c);
        S = [S; sd_label(sd_summary(D, 'times_seen_before', Xs, 'N', 'valid'), {'condition','group'}, {cond_name{c}, gname{gi+1}})]; %#ok<AGROW>
        T = [T; [table(pid(grp == gi), 'VariableNames', {'participant'}), ...
                 sd_label(array2table(D, 'VariableNames', sd_names('seen_%d', Xs)), {'group','condition'}, {gname{gi+1}, cond_name{c}})]]; %#ok<AGROW>
    end
    C = [C; sd_label(fig7_welch(prepeat(grp == 1, :, c), prepeat(grp == 0, :, c), Xs, 'times_seen_before'), {'condition'}, {cond_name{c}})]; %#ok<AGROW>
end
[r, chk.(sh)] = sd_block(outfile, sh, r, 'Summary: p(repeat next) by times seen before', S, chk.(sh));
[r, chk.(sh)] = sd_block(outfile, sh, r, 'Tests: streaking minus non-streaking (two-sided Welch t-tests, FDR)', C, chk.(sh));
[~, chk.(sh)] = sd_block(outfile, sh, r, 'Participant level: p(repeat next) by times seen before', T, chk.(sh));

%% Fig 7c ---------------------------------------------------------------------
sh = 'Fig7c'; r = 1; chk.(sh) = 0;
X   = 2:20;
pol = {'target-guided', dir_v, 1; 'uncertainty-guided', dir_c, 2};
S = table(); C = table(); T = table();
for i = [2 1]
    c = pol{i,3};
    for gi = [1 0]
        D = pol{i,2}(grp == gi, X, c);
        S = [S; sd_label(sd_summary(D, 'sampling_trial', X), {'policy','condition','group'}, {pol{i,1}, cond_name{c}, gname{gi+1}})]; %#ok<AGROW>
        T = [T; [table(pid(grp == gi), 'VariableNames', {'participant'}), ...
                 sd_label(array2table(D, 'VariableNames', sd_names('trial_%d', X)), {'group','policy','condition'}, {gname{gi+1}, pol{i,1}, cond_name{c}})]]; %#ok<AGROW>
    end
    C = [C; sd_label(fig7_welch(pol{i,2}(grp == 1, X, c), pol{i,2}(grp == 0, X, c), 1:numel(X), 'sampling_trial', X), ...
                     {'policy','condition'}, {pol{i,1}, cond_name{c}})]; %#ok<AGROW>
end
[r, chk.(sh)] = sd_block(outfile, sh, r, 'Summary: fraction of policy-aligned choices', S, chk.(sh));
[r, chk.(sh)] = sd_block(outfile, sh, r, 'Tests: streaking minus non-streaking (two-sided Welch t-tests, FDR)', C, chk.(sh));
[~, chk.(sh)] = sd_block(outfile, sh, r, 'Participant level: fraction of policy-aligned choices at each sampling trial', T, chk.(sh));

%% Fig 7d ---------------------------------------------------------------------
sh = 'Fig7d'; r = 1; chk.(sh) = 0;
Am = nan(N, numel(seqLength));
for k = 1:numel(seqLength), Am(:, k) = pc_match{k}(:, end); end
acc = {Am, pc_guess};
S = table(); C = table(); T = table();
for c = [2 1]
    for gi = [1 0]
        D = acc{c}(grp == gi, :);
        S = [S; sd_label(sd_summary(D, 'sequence_length', seqLength), {'condition','group'}, {cond_name{c}, gname{gi+1}})]; %#ok<AGROW>
        T = [T; [table(pid(grp == gi), 'VariableNames', {'participant'}), ...
                 sd_label(array2table(D, 'VariableNames', sd_names('length_%d', seqLength)), {'group','condition'}, {gname{gi+1}, cond_name{c}})]]; %#ok<AGROW>
    end
    x1 = acc{c}(grp == 1, :); x2 = acc{c}(grp == 0, :);
    x1 = [x1, mean(x1, 2)]; x2 = [x2, mean(x2, 2)];        %#ok<AGROW> % last column = mean over lengths
    [~, p, ~, st] = ttest2(x1, x2, 'Vartype', 'unequal');
    pH = p; pH(1:4) = Bonf_Holm_yc(p(1:4));
    d  = (mean(x1, 'omitnan') - mean(x2, 'omitnan')) ./ sqrt((var(x1, 'omitnan') + var(x2, 'omitnan')) / 2);
    Ct = table([sd_names('%d', seqLength), {'mean over lengths'}]', st.tstat(:), st.df(:), d(:), p(:), [pH(1:4)'; NaN], ...
               double([pH(1:4)' < 0.05; NaN]), ...
               'VariableNames', {'sequence_length','t','df','cohen_d','P_uncorrected','P_Holm','asterisk'});
    C = [C; sd_label(Ct, {'condition'}, {cond_name{c}})]; %#ok<AGROW>
end
[r, chk.(sh)] = sd_block(outfile, sh, r, 'Summary: accuracy by sequence length and subgroup', S, chk.(sh));
[r, chk.(sh)] = sd_block(outfile, sh, r, 'Tests: streaking minus non-streaking (two-sided Welch t-tests; Holm-Bonferroni across lengths)', C, chk.(sh));
[~, chk.(sh)] = sd_block(outfile, sh, r, 'Participant level: accuracy by sequence length', T, chk.(sh));

