%% Local functions --------------------------------------------------------------
function C = fig7_welch(D1, D0, cols, xname, xval)
% Welch t-tests streaking (D1) minus non-streaking (D0) on every column, FDR across
% all columns (as in fig7abcd.m), reported for the plotted columns "cols".
if nargin < 5, xval = cols; end
[~, p, ~, st] = ttest2(D1, D0, 'Vartype', 'unequal');
q  = mafdr(p(:), 'BHFDR', true);
md = mean(D1, 1, 'omitnan') - mean(D0, 1, 'omitnan');
C  = table(xval(:), md(cols)', st.tstat(cols)', st.df(cols)', p(cols)', q(cols), double(q(cols) < 0.005), ...
           'VariableNames', {xname, 'mean_difference_streaking_minus_nonstreaking', 't', 'df', 'P', 'q_FDR', 'thick_line'});
end
