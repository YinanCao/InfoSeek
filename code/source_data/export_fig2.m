% EXPORT_FIG2  Write the Source Data for Figure 2 to source_data/SourceData_Fig2.xlsx.
%
% Runs the finalized figure script code/figures/fig2.m unchanged, then writes,
% for each panel, the plotted summary (mean and 95% CI, plus the per-point tests
% behind the thick significance lines) followed by the participant-level values
% the summary is computed from. One sheet per panel, plus a README sheet.
%
% Usage (from any folder):
%   run('<path to InfoSeek_clean>/code/source_data/export_fig2.m')

addpath(fileparts(mfilename('fullpath')));   % helper functions sd_*.m
run(fullfile(fileparts(fileparts(fileparts(mfilename('fullpath')))), 'setup_paths.m'));
fig2;   % finalized figure script; note that it clears the workspace

root    = fileparts(fileparts(fileparts(mfilename('fullpath'))));
outfile = fullfile(root, 'source_data', 'SourceData_Fig2.xlsx');
if isfile(outfile), delete(outfile); end

pid  = unique_ids(:);              % anonymised participant numbers, row order of all matrices
cond_name = {'match', 'guess'};
chk  = struct();                   % numeric checksums per sheet, for the read-back check

%% README -----------------------------------------------------------------
readme = {
  'Source Data for Figure 2 (Human behavior).'
  'Generated by code/source_data/export_fig2.m from the figure script code/figures/fig2.m (https://github.com/YinanCao/InfoSeek).'
  sprintf('n = %d participants. "participant" is the anonymised participant number used in the data files.', nsubj)
  'Each sheet holds one panel: first the plotted summary, then the participant-level values it is computed from.'
  '95% CI = mean +/- 1.96 x SD / sqrt(n) across participants, as plotted.'
  'Per-point tests: t, df, exact P, and q_FDR (Benjamini-Hochberg adjusted P across the points of the curve). thick_line = 1 where q_FDR < 0.005, as drawn in the figure.'
  'Empty cells: no data (for example, choice positions beyond the length of the game).'
  ''
  'Sheets'
  'Fig2a: accuracy. match: probability of choosing the option linked to the target colour, by choice position, in games where the two bags are linked to opposite colours (lines; circles = last choice). guess: final-probe accuracy by sequence length (circles).'
  'Fig2b: fraction of choices aligned with the target-guided policy (match) and the uncertainty-guided policy (match and guess), sampling trials 2 to 20. Tests: one-sided one-sample t-tests against 0.5; uncertainty-guided contrast: two-sided paired t-tests, guess minus match.'
  'Fig2c: p(repeat next) by the number of times the current option has been sampled (left, 1 to 10) and by signed evidence in logLR (right; target-aligned in match, belief-aligned in guess). Contrasts: two-sided paired t-tests, guess minus match.'
  'Fig2d: choice-to-choice similarity (1 = same option chosen at choices i and j), pooled over sequence lengths. Grand-mean matrix as plotted (lower triangle, i > j), then participant-level values for each pair.'
  };
writecell(readme, outfile, 'Sheet', 'README', 'Range', 'A1');

%% Fig 2a -------------------------------------------------------------------
sh = 'Fig2a'; r = 1; chk.(sh) = 0;
% summary: match, by sequence length and choice position (positions 2..L plotted)
S = table();
for k = 1:numel(seqLength)
    L  = seqLength(k);
    Tk = sd_summary(pc_match{k}(:,2:L), 'choice_position', 2:L);
    Tk = [table(repmat({'match'},height(Tk),1), repmat(L,height(Tk),1), ...
                'VariableNames', {'condition','sequence_length'}), Tk]; %#ok<AGROW>
    S  = [S; Tk]; %#ok<AGROW>
end
[r, chk.(sh)] = sd_block(outfile, sh, r, 'Summary, match: accuracy by choice position (circles in the figure = last choice of each length)', S, chk.(sh));
% summary: guess, by sequence length
S = sd_summary(guessPc_human, 'sequence_length', seqLength);
S = [table(repmat({'guess'},height(S),1), 'VariableNames', {'condition'}), S];
[r, chk.(sh)] = sd_block(outfile, sh, r, 'Summary, guess: final-probe accuracy by sequence length', S, chk.(sh));
% participant level: match
A = []; P = []; Lc = [];
for k = 1:numel(seqLength)
    L = seqLength(k);
    Ak = nan(nsubj, 20); Ak(:,1:L) = pc_match{k};
    A = [A; Ak]; P = [P; pid]; Lc = [Lc; repmat(L, nsubj, 1)]; %#ok<AGROW>
end
T = array2table([P Lc A], 'VariableNames', [{'participant','sequence_length'}, sd_names('choice_%d', 1:20)]);
[r, chk.(sh)] = sd_block(outfile, sh, r, 'Participant level, match: accuracy at each choice position', T, chk.(sh));
% participant level: guess
T = array2table([pid guessPc_human], 'VariableNames', [{'participant'}, sd_names('length_%d', seqLength)]);
[~, chk.(sh)] = sd_block(outfile, sh, r, 'Participant level, guess: final-probe accuracy by sequence length', T, chk.(sh));

%% Fig 2b -------------------------------------------------------------------
sh = 'Fig2b'; r = 1; chk.(sh) = 0;
X  = 2:20;
pol = {'target-guided', dir_v, 1; 'uncertainty-guided', dir_c, 1; 'uncertainty-guided', dir_c, 2};
S = table();
for i = 1:size(pol,1)
    D  = pol{i,2}(:, X, pol{i,3});
    Ti = sd_summary(D, 'sampling_trial', X);
    Ti = sd_ttest(Ti, D, 0.5, 'right', 0.005);
    Ti = [table(repmat(pol(i,1),height(Ti),1), repmat(cond_name(pol{i,3}),height(Ti),1), ...
                'VariableNames', {'policy','condition'}), Ti]; %#ok<AGROW>
    S  = [S; Ti]; %#ok<AGROW>
end
[r, chk.(sh)] = sd_block(outfile, sh, r, 'Summary: policy alignment (tests: one-sided one-sample t-tests against 0.5)', S, chk.(sh));
D = dir_c(:, X, 2) - dir_c(:, X, 1);
S = sd_ttest(sd_summary(D, 'sampling_trial', X), D, 0, 'both', 0.005);
S = [table(repmat({'uncertainty-guided'},height(S),1), repmat({'guess minus match'},height(S),1), ...
           'VariableNames', {'policy','contrast'}), S];
[r, chk.(sh)] = sd_block(outfile, sh, r, 'Summary: uncertainty-guided contrast, guess minus match (two-sided paired t-tests)', S, chk.(sh));
T = table();
for i = 1:size(pol,1)
    Ti = [table(pid, repmat(pol(i,1),nsubj,1), repmat(cond_name(pol{i,3}),nsubj,1), ...
                'VariableNames', {'participant','policy','condition'}), ...
          array2table(pol{i,2}(:, X, pol{i,3}), 'VariableNames', sd_names('trial_%d', X))];
    T = [T; Ti]; %#ok<AGROW>
end
[~, chk.(sh)] = sd_block(outfile, sh, r, 'Participant level: fraction of policy-aligned choices at each sampling trial', T, chk.(sh));

%% Fig 2c -------------------------------------------------------------------
sh = 'Fig2c'; r = 1; chk.(sh) = 0;
Xs = 1:10;                                  % times seen before (left)
Xe = evi_level(:)';                         % signed-evidence levels in logLR (right)
S = table();
for c = 1:2
    Tc = sd_summary(spstay_human(:, Xs, c), 'times_seen_before', Xs);
    S  = [S; [table(repmat(cond_name(c),height(Tc),1), 'VariableNames', {'condition'}), Tc]]; %#ok<AGROW>
end
[r, chk.(sh)] = sd_block(outfile, sh, r, 'Summary, left: p(repeat next) by times the current option was seen before', S, chk.(sh));
D = spstay_human(:, Xs, 2) - spstay_human(:, Xs, 1);
S = sd_ttest(sd_summary(D, 'times_seen_before', Xs), D, 0, 'both', 0.005);
S = [table(repmat({'guess minus match'},height(S),1), 'VariableNames', {'contrast'}), S];
[r, chk.(sh)] = sd_block(outfile, sh, r, 'Summary, left: contrast guess minus match (two-sided paired t-tests)', S, chk.(sh));
S = table();
for c = 1:2
    Tc = sd_summary(pSW(:, :, c), 'signed_evidence_logLR', Xe);
    S  = [S; [table(repmat(cond_name(c),height(Tc),1), 'VariableNames', {'condition'}), Tc]]; %#ok<AGROW>
end
[r, chk.(sh)] = sd_block(outfile, sh, r, 'Summary, right: p(repeat next) by signed evidence (logLR)', S, chk.(sh));
D = pSW(:, :, 2) - pSW(:, :, 1);
S = sd_ttest(sd_summary(D, 'signed_evidence_logLR', Xe), D, 0, 'both', 0.005);
S = [table(repmat({'guess minus match'},height(S),1), 'VariableNames', {'contrast'}), S];
[r, chk.(sh)] = sd_block(outfile, sh, r, 'Summary, right: contrast guess minus match (two-sided paired t-tests)', S, chk.(sh));
T = table();
for c = 1:2
    T = [T; [table(pid, repmat(cond_name(c),nsubj,1), 'VariableNames', {'participant','condition'}), ...
             array2table(spstay_human(:, Xs, c), 'VariableNames', sd_names('seen_%d', Xs))]]; %#ok<AGROW>
end
[r, chk.(sh)] = sd_block(outfile, sh, r, 'Participant level, left: p(repeat next) by times seen before', T, chk.(sh));
T = table();
for c = 1:2
    T = [T; [table(pid, repmat(cond_name(c),nsubj,1), 'VariableNames', {'participant','condition'}), ...
             array2table(pSW(:, :, c), 'VariableNames', sd_names('logLR_%+.3f', Xe))]]; %#ok<AGROW>
end
[~, chk.(sh)] = sd_block(outfile, sh, r, 'Participant level, right: p(repeat next) by signed evidence (column = logLR value)', T, chk.(sh));

%% Fig 2d -------------------------------------------------------------------
sh = 'Fig2d'; r = 1; chk.(sh) = 0;
[jj, ii] = meshgrid(1:20, 1:20);           % ii = choice i (row), jj = choice j (column)
low = ii > jj;                             % strictly lower triangle, as plotted
for c = 1:2
    M = squeeze(mean(ch2chM(:,:,:,c), 1)); % grand mean, as plotted
    M(~low) = NaN;
    T = [table((1:20)', 'VariableNames', {'choice_i'}), array2table(M, 'VariableNames', sd_names('choice_j_%d', 1:20))];
    [r, chk.(sh)] = sd_block(outfile, sh, r, sprintf('Summary, %s: grand-mean similarity matrix (rows = choice i, columns = choice j)', cond_name{c}), T, chk.(sh));
end
pairs = sd_names('i%d_j%d', [ii(low) jj(low)]');
T = table();
for c = 1:2
    V = reshape(ch2chM(:,:,:,c), nsubj, 400);
    T = [T; [table(pid, repmat(cond_name(c),nsubj,1), 'VariableNames', {'participant','condition'}), ...
             array2table(V(:, low(:)), 'VariableNames', pairs)]]; %#ok<AGROW>
end
[~, chk.(sh)] = sd_block(outfile, sh, r, 'Participant level: similarity for each pair of choices (column iX_jY = choices X and Y)', T, chk.(sh));

%% Read-back check ------------------------------------------------------------
sd_readback(outfile, chk);
