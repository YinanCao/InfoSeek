"""Write the Source Data for Figure 6 to source_data/SourceData_Fig6.xlsx.

Runs the finalized figure scripts code/figures/fig6bc.py (Fig. 6b, c) and
code/figures/fig6d.py (Fig. 6d) unchanged, then writes one sheet per panel:
the plotted summary first, then the values for each of the 25 RNN instances.

Usage (from any folder):
    python <path to InfoSeek_clean>/code/source_data/export_fig6.py
Requires pandas and openpyxl in addition to the packages used by the figure scripts.
"""
import runpy
from pathlib import Path

import numpy as np
import pandas as pd
import matplotlib

matplotlib.use("Agg")                      # draw off-screen; the figure scripts' own
matplotlib.use = lambda *args, **kw: None  # backend request is ignored
import matplotlib.pyplot as plt
plt.show = lambda *args, **kw: None

ROOT = Path(__file__).resolve().parents[2]
FIG = ROOT / "code" / "figures"
OUT = ROOT / "source_data" / "SourceData_Fig6.xlsx"


def to_np(a):
    """Tensor or array to a float64 numpy array."""
    return np.asarray(a.detach().cpu().numpy() if hasattr(a, "detach") else a, dtype=float)


def summary(D, xname, xvals):
    """Mean and 95% CI across RNN instances (rows of D), as plotted: mean +/- 1.96 x SD / sqrt(n)."""
    n = np.sum(~np.isnan(D), axis=0)
    m = np.nanmean(D, axis=0)
    hw = 1.96 * np.nanstd(D, axis=0, ddof=1) / np.sqrt(D.shape[0])
    return pd.DataFrame({xname: np.asarray(xvals), "n": n, "mean": m,
                         "CI95_lower": m - hw, "CI95_upper": m + hw})


def label(df, **cols):
    """Prepend constant label columns."""
    for i, (k, v) in enumerate(cols.items()):
        df.insert(i, k, v)
    return df


class Sheet:
    """Writes titled blocks one below the other and keeps a sum of the numbers written."""

    def __init__(self, writer, name):
        self.writer, self.name, self.row, self.total = writer, name, 0, 0.0

    def block(self, title, df):
        df.to_excel(self.writer, sheet_name=self.name, startrow=self.row + 1, index=False)
        self.writer.sheets[self.name].cell(row=self.row + 1, column=1, value=title)
        num = df.select_dtypes(include=[np.number]).to_numpy(dtype=float)
        self.total += np.nansum(num)
        self.row += len(df) + 4          # title + header + rows + 2 blank rows


# --- run the finalized figure scripts ---------------------------------------
# keep only the plotted variables of each script, to limit memory use
_g = runpy.run_path(str(FIG / "fig6bc.py"), run_name="__main__")
g = {k: _g[k] for k in ["subjects", "n_games", "accuracy", "accuracy_Bayes", "human_mean", "human_sem",
                        "x_human", "bin_centers", "pv_z", "pc_z", "pr_z", "pr_signed_z"]}
del _g
plt.close("all")
_h = runpy.run_path(str(FIG / "fig6d.py"), run_name="__main__")
h = {k: _h[k] for k in ["n_games", "state_traj_all", "EFF_dim"]}
del _h
plt.close("all")

inst = np.array(list(g["subjects"]))                      # RNN instance numbers (1..25)
net_bc = ["match RNN", "guess RNN (state only)", "guess RNN (state + meta)"]   # model order in fig6bc.py
net_d = ["match RNN (choose orange)", "match RNN (choose blue)",
         "guess RNN (state only)", "guess RNN (state + meta)"]              # network order in fig6d.py
cond_d = ["[0,0]", "[0,1]", "[1,0]", "[1,1]"]                              # bag 1, bag 2 dominant colour (1 = orange, 0 = blue)

readme = [
    "Source Data for Figure 6 (RNNs, sampling patterns, and representational geometry).",
    "Generated by code/source_data/export_fig6.py from the figure scripts code/figures/fig6bc.py and code/figures/fig6d.py (https://github.com/YinanCao/InfoSeek).",
    f"n = {len(inst)} RNN instances per network type. \"instance\" is the instance number used in the file names of code/rnn/saved_runs.",
    "95% CI = mean +/- 1.96 x SD / sqrt(n) across RNN instances, as plotted.",
    f"Test games per instance and sequence length: {g['n_games']} (Fig6b, Fig6c) and {h['n_games']} (Fig6d).",
    "",
    "Sheets",
    "Fig6b: guess accuracy by sequence length for the two guess RNNs and the Bayes-optimal agent, and human accuracy (mean and 95% CI as plotted, n = 420; participant-level values are in SourceData_Fig2.xlsx, sheet Fig2a, guess).",
    "Fig6c: RNN sampling behaviour: target-guided policy alignment (match RNN), uncertainty-guided policy alignment, p(repeat next) by times seen before, and p(repeat next) by signed evidence (logLR bin centres).",
    "Fig6d: hidden-state trajectories in the shared PC space (PC1 to PC3, as plotted), averaged over RNN instances and over games of each bag-colour mapping, by number of samples seen (0 = before the first sample; circles in the figure at 8, 12, 16 and 20). Mapping [a,b]: dominant colour of bag 1 and bag 2 (1 = orange, 0 = blue). Effective dimensionality d (participation ratio of the uncentered activity) for each RNN instance, and its mean and 95% CI.",
]

OUT.parent.mkdir(parents=True, exist_ok=True)
totals = {}
with pd.ExcelWriter(OUT, engine="openpyxl") as w:
    pd.DataFrame({"README": readme}).to_excel(w, sheet_name="README", index=False, header=False)

    # --- Fig 6b ---------------------------------------------------------------
    s = Sheet(w, "Fig6b")
    acc = to_np(g["accuracy"])                 # instances x sequence length (1..20) x models
    accB = to_np(g["accuracy_Bayes"])
    L = np.arange(1, acc.shape[1] + 1)
    curves = {"guess RNN (state only)": acc[:, :, 1], "guess RNN (state + meta)": acc[:, :, 2],
              "Bayes-optimal": accB[:, :, 2]}
    S = pd.concat([label(summary(D, "sequence_length", L), data=k) for k, D in curves.items()], ignore_index=True)
    s.block("Summary: guess accuracy by sequence length (RNNs and Bayes-optimal agent)", S)
    hm, hci = to_np(g["human_mean"]), to_np(g["human_sem"])   # human_sem in fig6bc.py is already x 1.96
    S = pd.DataFrame({"data": "human", "sequence_length": to_np(g["x_human"]).astype(int), "n": 420,
                      "mean": hm, "CI95_lower": hm - hci, "CI95_upper": hm + hci})
    s.block("Summary: human guess accuracy (as plotted; participant-level values in SourceData_Fig2.xlsx, sheet Fig2a)", S)
    T = pd.concat([label(pd.DataFrame(D, columns=[f"length_{l}" for l in L]), instance=inst, data=k)
                   for k, D in curves.items()], ignore_index=True)
    s.block("RNN-instance level: guess accuracy by sequence length", T)
    totals[s.name] = s.total

    # --- Fig 6c ---------------------------------------------------------------
    s = Sheet(w, "Fig6c")
    bc = to_np(g["bin_centers"])
    sub = [("target-guided policy alignment", "sampling_trial", np.arange(2, 21), to_np(g["pv_z"]), [0]),
           ("uncertainty-guided policy alignment", "sampling_trial", np.arange(2, 21), to_np(g["pc_z"]), [0, 1, 2]),
           ("p(repeat next) by times seen before", "times_seen_before", np.arange(1, 11), to_np(g["pr_z"]), [0, 1, 2]),
           ("p(repeat next) by signed evidence", "signed_evidence_logLR", bc, to_np(g["pr_signed_z"]), [0, 1, 2])]
    for title, xname, xv, arr, nets in sub:            # arr: instances x networks x points
        S = pd.concat([label(summary(arr[:, m, :], xname, xv), network=net_bc[m]) for m in nets], ignore_index=True)
        s.block(f"Summary: {title}", S)
        cols = [f"logLR_{v:+.3f}" for v in xv] if xname == "signed_evidence_logLR" else [f"{xname}_{v}" for v in xv]
        T = pd.concat([label(pd.DataFrame(arr[:, m, :], columns=cols), instance=inst, network=net_bc[m])
                       for m in nets], ignore_index=True)
        s.block(f"RNN-instance level: {title}", T)
    totals[s.name] = s.total

    # --- Fig 6d ---------------------------------------------------------------
    s = Sheet(w, "Fig6d")
    traj = to_np(h["state_traj_all"])            # networks x mappings x time (0..20) x PCs
    rows = []
    for i, net in enumerate(net_d):
        for j, cnd in enumerate(cond_d):
            for t in range(traj.shape[2]):
                rows.append({"network": net, "bag_colour_mapping": cnd, "samples_seen": t,
                             "PC1": traj[i, j, t, 0], "PC2": traj[i, j, t, 1], "PC3": traj[i, j, t, 2],
                             "circle_in_figure": int(t in (8, 12, 16, 20))})
    s.block("Trajectories: mean hidden state in the shared PC space (PC1 to PC3, as plotted)", pd.DataFrame(rows))
    eff = to_np(h["EFF_dim"])                    # instances x networks
    S = pd.concat([label(summary(eff[:, [i]], "dummy", [0]).drop(columns="dummy"), network=net)
                   for i, net in enumerate(net_d)], ignore_index=True)
    s.block("Summary: effective dimensionality d", S)
    T = label(pd.DataFrame(eff, columns=[f"d_{n}" for n in net_d]), instance=inst)
    s.block("RNN-instance level: effective dimensionality d", T)
    totals[s.name] = s.total

# --- read-back check -----------------------------------------------------------
back = pd.read_excel(OUT, sheet_name=None, header=None)
for name, total in totals.items():
    got = np.nansum(back[name].apply(pd.to_numeric, errors="coerce").to_numpy(dtype=float))
    assert abs(got - total) <= 1e-6 * max(1.0, abs(total)), f"Read-back mismatch in sheet {name}"
print(f"Source Data written and checked: {OUT}")
