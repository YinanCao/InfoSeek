% EXPORT_FIG8  Write the Source Data for Figure 8 to source_data/SourceData_Fig8.xlsx.
%
% Runs the finalized figure script code/figures/fig8.m unchanged. The statistics
% are taken from the tables that fig8.m itself builds for the Supplementary Tables
% (struct "stats"; same values and P-value format as Supplementary Tables 1-4),
% with numbers stored as numbers. The participant-level variables entering the
% regressions and mediation analyses follow below them.
%
% Usage (from any folder):
%   run('<path to InfoSeek_clean>/code/source_data/export_fig8.m')

addpath(fileparts(mfilename('fullpath')));   % helper functions sd_*.m
run(fullfile(fileparts(fileparts(fileparts(mfilename('fullpath')))), 'setup_paths.m'));
fig8;   % finalized figure script; note that it clears the workspace

root    = fileparts(fileparts(fileparts(mfilename('fullpath'))));
outfile = fullfile(root, 'source_data', 'SourceData_Fig8.xlsx');
if isfile(outfile), delete(outfile); end
chk = struct();

sd_readme(outfile, {
  'Source Data for Figure 8 (Relationships between performance, policy, cognitive ability, and psychological traits).'
  'Generated by code/source_data/export_fig8.m from the figure script code/figures/fig8.m (https://github.com/YinanCao/InfoSeek).'
  sprintf('Guess condition. n = %d participants for Fig8a; n = %d for Fig8b (NFCS regression: n = %d after excluding %d outliers with |Pearson residual| > %.1f).', ...
          nsub, nB, sum(~nfcs_out), sum(nfcs_out), NFCS_RESID_Z)
  '"participant" is the anonymised participant number used in the data files.'
  'Coefficients are standardized (all variables z-scored before fitting). Coefficient, CI and t are rounded as in the Supplementary Tables (3 decimals; 4 for the mediation table). P: exact to 3 decimals, "< 0.001" below 0.001; "*" marks P < 0.05, as the asterisks in the figure.'
  ''
  'Sheets'
  'Fig8a: regression of guess accuracy (mean over sequence lengths) on model parameters for human accuracy and for the accuracy predicted by the noisy-inferences and noisy-responses models (top and middle rows); the same regression for each sequence length, beta_c and EoS (bottom row). Participant-level accuracy and parameters follow (raw values, before z-scoring).'
  'Fig8b: regressions of NFCS and ICAR on model parameters (middle), mediation analyses (right; robust HC3 standard errors, percentile bootstrap for the indirect effect), and participant-level scores, accuracy and parameters (raw values; the NFCS and ICAR columns are the distributions on the left).'
  });

%% Fig 8a ---------------------------------------------------------------------
sh = 'Fig8a'; r = 1; chk.(sh) = 0;
typ = {'acc_human', 'acc_noisy_inferences', 'acc_noisy_responses'};
for i = 1:3
    T = stats.S1.(typ{i});
    [r, chk.(sh)] = sd_block(outfile, sh, r, ['Top/middle rows: ' T.Properties.Description], fig8_tbl(T, 'coef'), chk.(sh));
end
for i = 1:3
    T = stats.S2.(typ{i});
    [r, chk.(sh)] = sd_block(outfile, sh, r, ['Bottom row: ' T.Properties.Description], fig8_tbl(T, 'length'), chk.(sh));
end
acc_names = {'human', 'noisy_inferences', 'noisy_responses'};
len_names = [sd_names('L%d', [8 12 16 20]), {'mean'}];
vn = {}; V = [];
for i = 1:3
    vn = [vn, strcat({['acc_' acc_names{i} '_']}, len_names)]; %#ok<AGROW>
    V  = [V, squeeze(dvs(:, i, :))];                          %#ok<AGROW>
end
T = [table(subjlist(:), 'VariableNames', {'participant'}), array2table(V, 'VariableNames', vn), ...
     array2table(parameter, 'VariableNames', {'EoS','beta_c','beta_r','leak_delta','noise_sigma'}), ...
     array2table(parameter_exact, 'VariableNames', {'EoS_noisy_responses_model','beta_c_noisy_responses_model', ...
                                                    'beta_r_noisy_responses_model','sigma_resp_noisy_responses_model'})];
[~, chk.(sh)] = sd_block(outfile, sh, r, ...
    'Participant level: accuracy (by sequence length and mean) and model parameters (EoS = ELBO free theta minus ELBO fixed theta)', T, chk.(sh));

%% Fig 8b ---------------------------------------------------------------------
sh = 'Fig8b'; r = 1; chk.(sh) = 0;
reg = {'NFCS_excl', 'regression plotted in Fig. 8b'; ...
       'ICAR',      'regression plotted in Fig. 8b'; ...
       'NFCS_all',  'not plotted; Supplementary Table 3'};
for i = 1:size(reg, 1)
    T = stats.S3.(reg{i,1});
    [r, chk.(sh)] = sd_block(outfile, sh, r, sprintf('Middle (%s): %s', reg{i,2}, T.Properties.Description), fig8_tbl(T, 'coef'), chk.(sh));
end
med = {'NFCS_via_EoS', 'mediation shown in Fig. 8b'; ...
       'ICAR_via_betac', 'mediation shown in Fig. 8b'; ...
       'EoS_via_NFCS', 'reverse model; Supplementary Table 4'; ...
       'betac_via_ICAR', 'reverse model; Supplementary Table 4'};
for i = 1:size(med, 1)
    T = stats.S4.(med{i,1});
    [r, chk.(sh)] = sd_block(outfile, sh, r, sprintf('Right (%s): %s', med{i,2}, T.Properties.Description), fig8_tbl(T, 'mediation'), chk.(sh));
end
keep = ~badscore;
T = [table(subjlist(keep), 'VariableNames', {'participant'}), ...
     array2table(score(keep, :), 'VariableNames', {'Big5_Extraversion','Big5_Agreeableness','Big5_Conscientiousness', ...
                                                   'Big5_NegativeEmotionality','Big5_OpenMindedness','ICAR','NFCS'}), ...
     table(acc_B(keep), 'VariableNames', {'acc_human_mean'}), ...
     array2table(parameter(keep, :), 'VariableNames', {'EoS','beta_c','beta_r','leak_delta','noise_sigma'}), ...
     table(age(keep), sex(keep), double(nfcs_out(:)), ...
           'VariableNames', {'age','sex_female','NFCS_outlier_excluded'})];
[~, chk.(sh)] = sd_block(outfile, sh, r, ...
    'Participant level: scores, accuracy, model parameters and covariates (raw values; z-scored within this sample before fitting)', T, chk.(sh));

%% Read-back check ------------------------------------------------------------
sd_readback(outfile, chk);

%% Local functions --------------------------------------------------------------
function T = fig8_tbl(T, kind)
% Readable column names and numbers stored as numbers for a fig8.m statistics table
% (the tables are cell arrays of formatted strings). P values stay as formatted text.
switch kind
    case 'coef'
        tname = T.Properties.VariableNames{5};
        dfv   = regexp(tname, '\d+', 'match', 'once');
        if isempty(dfv), tcol = 't'; else, tcol = sprintf('t (df = %s)', dfv); end
        names = {'term', 'coefficient', 'CI95_lower', 'CI95_upper', tcol, 'P'};
    case 'length'
        names = {'sequence_length', 'regressor', 'coefficient', 'CI95_lower', 'CI95_upper', 't', 'df', 'P'};
    case 'mediation'
        names = {'path', 'coefficient', 'CI95_lower', 'CI95_upper', 't', 'P'};
end
T.Properties.VariableNames = names;
for v = 1:width(T) - 1                       % last column (P) stays text
    x = T.(v);
    if iscell(x)
        y = str2double(x);
        if all(~isnan(y) | cellfun(@isempty, x)) && any(~isnan(y))
            T.(v) = y;
        end
    end
end
end
