% EXPORT_FIG3  Write the Source Data for Figure 3b to source_data/SourceData_Fig3.xlsx.
%
% Runs the finalized figure script code/figures/fig3b.m unchanged and writes the
% values it plots. Fig. 3b is an illustrative example sequence: the beliefs and
% choices are set in fig3b.m, they are not data from a participant.
% Fig. 3a is a schematic and has no source data.
%
% Usage (from any folder):
%   run('<path to InfoSeek_clean>/code/source_data/export_fig3.m')

addpath(fileparts(mfilename('fullpath')));   % helper functions sd_*.m
run(fullfile(fileparts(fileparts(fileparts(mfilename('fullpath')))), 'setup_paths.m'));
fig3b;   % finalized figure script; note that it clears the workspace

root    = fileparts(fileparts(fileparts(mfilename('fullpath'))));
outfile = fullfile(root, 'source_data', 'SourceData_Fig3.xlsx');
if isfile(outfile), delete(outfile); end
chk = struct();

xline_trials = [5 11];   % vertical lines drawn in fig3b.m: end of the streak on option 1, then on option 2

sd_readme(outfile, {
  'Source Data for Figure 3b (Computational model: example sequence).'
  'Generated by code/source_data/export_fig3.m from the figure script code/figures/fig3b.m (https://github.com/YinanCao/InfoSeek).'
  'Illustrative example sequence: the beliefs and choices are set in fig3b.m; they are not data from a participant. Fig. 3a is a schematic and has no source data.'
  'Option 1 is drawn with pentagons and option 2 with triangles. Lines: belief about each option (thick while that option is being sampled).'
  sprintf('Grey horizontal lines: threshold +/- theta, theta = %.2f. Vertical lines after trials %d and %d: the belief about the sampled option crossed the threshold.', theta, xline_trials)
  sprintf('Colour of each shape: signed evidence of that sample on a blue-grey-orange scale (pure blue at -%.4f logLR or below, grey at 0, pure orange at +%.4f or above); RGB values given.', mev, mev)
  });

%% Fig 3b -----------------------------------------------------------------------
sh = 'Fig3b'; r = 1; chk.(sh) = 0;
T = table((0:nsmp)', belief(:, 1), belief(:, 2), ...
          'VariableNames', {'samples_seen', 'belief_option1', 'belief_option2'});
[r, chk.(sh)] = sd_block(outfile, sh, r, 'Belief trajectories (lines; samples_seen = 0 before the first sample)', T, chk.(sh));

trial = (1:nsmp)';
evc   = ev(sub2ind(size(ev), trial, choice));          % evidence of the sampled option on each trial
pos   = belief(sub2ind(size(belief), trial + 1, choice)); % vertical position of each shape
rgb   = cell2mat(arrayfun(@(e) fig3_colour(e, mev), evc, 'UniformOutput', false));
shape = repmat({'pentagon'}, nsmp, 1); shape(choice == 2) = {'triangle'};
T = table(trial, choice, shape, evc, pos, rgb(:,1), rgb(:,2), rgb(:,3), double(ismember(trial, xline_trials)), ...
          'VariableNames', {'sampling_trial', 'sampled_option', 'shape', 'signed_evidence_logLR', ...
                            'belief_after_sample', 'colour_R', 'colour_G', 'colour_B', 'vertical_line_after_trial'});
[r, chk.(sh)] = sd_block(outfile, sh, r, 'Samples (shapes): sampled option, evidence of the sample (colour) and updated belief (vertical position)', T, chk.(sh));

T = table({'theta'; 'colour scale limit (logLR)'}, [theta; mev], 'VariableNames', {'quantity', 'value'});
[~, chk.(sh)] = sd_block(outfile, sh, r, 'Constants used in the figure', T, chk.(sh));

%% Read-back check ------------------------------------------------------------
sd_readback(outfile, chk);

%% Local functions --------------------------------------------------------------
function col = fig3_colour(y, m)
% Same colour scale as evidenceColor in fig3b.m (blue - grey - orange).
blue   = [0 0.5 1];
gray   = [0.5 0.5 0.5];
orange = [1 0.5 0];
y = max(-m, min(m, y));
if y < 0
    t = (y + m) / m;
    col = blue * (1 - t) + gray * t;
else
    t = y / m;
    col = gray * (1 - t) + orange * t;
end
end
