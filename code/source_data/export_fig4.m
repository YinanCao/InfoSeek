% EXPORT_FIG4  Write the Source Data for Figure 4 to source_data/SourceData_Fig4.xlsx.
%
% Runs the finalized figure script code/figures/fig4.m unchanged, then writes,
% for each panel, the plotted summary followed by the participant-level values.
% Set Nsim = 1000 in fig4.m before running, so that the Source Data and the
% published figure come from the same 1,000 simulations per participant.
%
% Usage (from any folder):
%   run('<path to InfoSeek_clean>/code/source_data/export_fig4.m')

addpath(fileparts(mfilename('fullpath')));   % helper functions sd_*.m
run(fullfile(fileparts(fileparts(fileparts(mfilename('fullpath')))), 'setup_paths.m'));
fig4;   % finalized figure script; note that it clears the workspace

root    = fileparts(fileparts(fileparts(mfilename('fullpath'))));
outfile = fullfile(root, 'source_data', 'SourceData_Fig4.xlsx');
if isfile(outfile), delete(outfile); end
if Nsim < 1000
    warning('export_fig4:Nsim', 'Nsim = %d in fig4.m; the Source Data should use Nsim = 1000.', Nsim);
end

pid       = unique_ids(:);
cond_name = {'match', 'guess'};
par_name  = {'leak_delta','noise_sigma','beta_v','beta_c','beta_r','theta','epsilon'};   % columns of "input"
chk       = struct();

%% README -----------------------------------------------------------------
sd_readme(outfile, {
  'Source Data for Figure 4 (Model fits and parameters).'
  'Generated by code/source_data/export_fig4.m from the figure script code/figures/fig4.m (https://github.com/YinanCao/InfoSeek).'
  sprintf('n = %d participants. "participant" is the anonymised participant number used in the data files.', nsubj)
  sprintf('Model values (Fig4a): for each participant, the mean over %d simulations of the full model with that participant''s best-fitting parameters.', Nsim)
  '95% CI = mean +/- 1.96 x SD / sqrt(n) across participants, as plotted.'
  'Empty cells: no data.'
  ''
  'Sheets'
  'Fig4a: human data (circles) and model simulations (lines) for the four behavioural signatures: target-guided policy alignment (match), uncertainty-guided policy alignment (match, guess), p(repeat next) by times seen before, and p(repeat next) by signed evidence (logLR).'
  'Fig4b: best-fitting parameters (mean and 95% CI as plotted; dots = participants). beta_v is fixed at 0 in the guess condition. Tests: (1) match minus guess, paired max-statistic sign-flip permutation test with FWE correction across the six parameters (10,000 permutations); (2) one-sample tests against 0 with max-statistic FWE correction (10,000 permutations). A P of 0 means that no permutation reached the observed statistic (P < 1/10,000).'
  'Fig4c: Spearman correlation of each parameter between the match and guess conditions. rho_bootstrap_mean and 95% CI from 10,000 bootstrap resamples of participants (recomputed by this exporter with rng(1234); values can differ from the figure titles in the last digit because of resampling). P = two-sided bootstrap P (twice the smaller tail proportion on either side of 0); 0 means P < 1/10,000.'
  });

%% Fig 4a -------------------------------------------------------------------
sh = 'Fig4a'; r = 1; chk.(sh) = 0;
sub = { % name, x name, x values, human data, model data, conditions
  'target-guided policy alignment',      'sampling_trial',        2:20,          dir_v_human(:,2:20,:), tmp1, 1
  'uncertainty-guided policy alignment', 'sampling_trial',        2:20,          dir_c_human(:,2:20,:), tmp2, [1 2]
  'p(repeat next) by times seen before', 'times_seen_before',     1:10,          spstay_human(:,1:10,:), tmp3, [1 2]
  'p(repeat next) by signed evidence',   'signed_evidence_logLR', evi_level(:)', pSW_human,             tmp4, [1 2]
  };
src = {'human', 'model'};
for i = 1:size(sub,1)
    S = table(); T = table();
    for c = sub{i,6}
        for k = 1:2
            D = sub{i,3+k}(:,:,c);
            S = [S; sd_label(sd_summary(D, sub{i,2}, sub{i,3}), {'data','condition'}, {src{k}, cond_name{c}})]; %#ok<AGROW>
            if strcmp(sub{i,2}, 'signed_evidence_logLR'), fmt = 'logLR_%+.3f'; else, fmt = [sub{i,2} '_%d']; end
            T = [T; [table(pid, 'VariableNames', {'participant'}), ...
                     sd_label(array2table(D, 'VariableNames', sd_names(fmt, sub{i,3})), {'data','condition'}, {src{k}, cond_name{c}})]]; %#ok<AGROW>
        end
    end
    [r, chk.(sh)] = sd_block(outfile, sh, r, sprintf('Summary: %s', sub{i,1}), S, chk.(sh));
    [r, chk.(sh)] = sd_block(outfile, sh, r, sprintf('Participant level: %s', sub{i,1}), T, chk.(sh));
end

%% Fig 4b -------------------------------------------------------------------
sh = 'Fig4b'; r = 1; chk.(sh) = 0;
S = table();
for c = 1:2
    for j = 1:numel(par_name)
        D  = input(:, j, c);
        ok = ~isnan(D);
        mu = mean(D(ok)); hw = 1.96 * std(D(ok)) / sqrt(sum(ok));     % as in draw_dataDistCI
        S  = [S; table({par_name{j}}, {cond_name{c}}, sum(ok), mu, mu - hw, mu + hw, ...
                 'VariableNames', {'parameter','condition','n','mean','CI95_lower','CI95_upper'})]; %#ok<AGROW>
    end
end
[r, chk.(sh)] = sd_block(outfile, sh, r, 'Summary: parameter estimates (mean and 95% CI, as plotted)', S, chk.(sh));
pp = [1 2 4 5 6 7];                                   % parameters in the paired test (beta_v excluded)
Dd = input(:, pp, 1) - input(:, pp, 2);
S  = table(par_name(pp)', mean(Dd, 1)', res.t_obs(:), repmat(nsubj - 1, numel(pp), 1), res.dz(:), res.p_unc(:), res.p_corr(:), ...
           'VariableNames', {'parameter','mean_difference_match_minus_guess','t','df','cohen_dz','P_uncorrected','P_FWE'});
[r, chk.(sh)] = sd_block(outfile, sh, r, 'Tests: match minus guess (paired max-statistic permutation test, FWE-corrected)', S, chk.(sh));
os_par  = {'beta_v','beta_c','beta_r','beta_c','beta_r'};
os_cond = {'match','match','match','guess','guess'};
S = table(os_par', os_cond', m(:), ci(:,1), ci(:,2), tObs(:), repmat(nSub - 1, numel(tObs), 1), pFWE(:), cohend(:), ...
          'VariableNames', {'parameter','condition','mean','CI95_lower_t','CI95_upper_t','t','df','P_FWE','cohen_d'});
[r, chk.(sh)] = sd_block(outfile, sh, r, 'Tests: one-sample tests against 0 (max-statistic sign-flip permutation, FWE-corrected; t-based 95% CI)', S, chk.(sh));
T = table();
for c = 1:2
    T = [T; [table(pid, 'VariableNames', {'participant'}), ...
             sd_label(array2table(input(:, :, c), 'VariableNames', par_name), {'condition'}, {cond_name{c}})]]; %#ok<AGROW>
end
[~, chk.(sh)] = sd_block(outfile, sh, r, 'Participant level: best-fitting parameters', T, chk.(sh));

%% Fig 4c -------------------------------------------------------------------
sh = 'Fig4c'; r = 1; chk.(sh) = 0;
rng(1234);
cp = [1 2 4 5 6 7];                                   % beta_v has no guess estimate (fixed at 0)
S  = table();
for j = cp
    x = input(:, j, 1); y = input(:, j, 2); n = numel(x);
    rb = nan(nboot, 1);
    for b = 1:nboot
        ib = randsample(n, n, true);
        rb(b) = corr(x(ib), y(ib), 'type', corr_type);
    end
    cib = prctile(rb, [2.5 97.5]);
    pb  = min(1, 2 * min(mean(rb <= 0), mean(rb >= 0)));
    S   = [S; table({par_name{j}}, n, corr(x, y, 'type', corr_type), mean(rb), cib(1), cib(2), pb, ...
                'VariableNames', {'parameter','n','rho_full_sample','rho_bootstrap_mean','CI95_lower','CI95_upper','P_bootstrap'})]; %#ok<AGROW>
end
[r, chk.(sh)] = sd_block(outfile, sh, r, sprintf('Summary: %s correlation between match and guess (%d bootstrap resamples)', corr_type, nboot), S, chk.(sh));
V  = reshape(permute(input(:, cp, :), [1 3 2]), nsubj, []);    % columns: param1 match, param1 guess, ...
vn = reshape([strcat(par_name(cp), '_match'); strcat(par_name(cp), '_guess')], 1, []);
T  = [table(pid, 'VariableNames', {'participant'}), array2table(V, 'VariableNames', vn)];
[~, chk.(sh)] = sd_block(outfile, sh, r, 'Participant level: parameter estimates in match (x axis) and guess (y axis)', T, chk.(sh));

%% Read-back check ------------------------------------------------------------
sd_readback(outfile, chk);
